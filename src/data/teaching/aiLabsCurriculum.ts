import type { TeachingLab } from './teachingTypes'

/**
 * Part X — AI Lab Curriculum & practical-test layer (28 labs across 7 families).
 * Each lab is structured (scenario, objectives, rubric, remediation)—not a single empty text box.
 *
 * Access model:
 * - public: selected guided/practice starters for trustworthy browsing
 * - signed_in: broader guided + practice continuity
 * - premium: test-style + advanced workflow/content/review depth (eligible plans—materials access, not outcomes)
 */

type AiLabInput = Omit<TeachingLab, 'libraryId' | 'conceptIds' | 'prerequisites'> &
  Partial<Pick<TeachingLab, 'libraryId' | 'conceptIds' | 'prerequisites'>>

function ai(p: AiLabInput): TeachingLab {
  return {
    ...p,
    libraryId: 'ai_foundations',
    conceptIds: p.conceptIds ?? [],
    prerequisites: p.prerequisites ?? [],
  }
}

